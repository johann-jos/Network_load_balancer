'use client';

import React, { useState } from 'react';
import { useSimulation } from '../context/SimulationContext';
import { simulateAlgorithmComparison } from '../lib/simulationEngine';
import { AlgorithmBenchmarkResult } from '../types/simulation';
import { BarChart3, Play, Info } from 'lucide-react';

export const AlgorithmComparison: React.FC = () => {
  const { servers } = useSimulation();
  const [benchmarkResults, setBenchmarkResults] = useState<AlgorithmBenchmarkResult[] | null>(null);
  const [isSimulating, setIsSimulating] = useState<boolean>(false);

  const runBenchmark = () => {
    setIsSimulating(true);
    setTimeout(() => {
      const results = simulateAlgorithmComparison(servers, 100);
      setBenchmarkResults(results);
      setIsSimulating(false);
    }, 400);
  };

  return (
    <div className="glass-panel border border-slate-800/80 rounded-2xl p-5 shadow-2xl space-y-5">
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between border-b border-slate-800/80 pb-3 gap-3">
        <div className="flex items-center space-x-2.5">
          <div className="p-1.5 bg-cyan-950/80 border border-cyan-500/40 rounded-lg text-cyan-400">
            <BarChart3 className="w-4 h-4" />
          </div>
          <div>
            <h2 className="text-sm font-bold text-white font-mono uppercase tracking-wider">
              Algorithm Performance Benchmark Suite
            </h2>
            <p className="text-[11px] text-slate-400">
              Run an identical 100-request simulated workload across RR, LC &amp; WRR side-by-side
            </p>
          </div>
        </div>

        <button
          onClick={runBenchmark}
          disabled={isSimulating}
          className="flex items-center justify-center space-x-2 px-5 py-2.5 bg-gradient-to-r from-cyan-500 to-blue-600 hover:from-cyan-400 hover:to-blue-500 text-slate-950 font-bold rounded-xl text-xs transition-all shadow-lg shadow-cyan-950/50 font-mono"
        >
          <Play className="w-4 h-4 fill-current" />
          <span>{isSimulating ? 'Simulating Workload...' : 'RUN BENCHMARK (100 REQ)'}</span>
        </button>
      </div>

      {/* Benchmark Results Table */}
      {benchmarkResults ? (
        <div className="space-y-4 animate-in fade-in duration-300">
          <div className="overflow-x-auto rounded-xl border border-slate-800/90 bg-slate-950/90 shadow-inner">
            <table className="w-full text-left font-mono text-xs">
              <thead className="bg-slate-900/90 text-slate-400 border-b border-slate-800">
                <tr>
                  <th className="p-3.5">Algorithm</th>
                  <th className="p-3.5">Workload</th>
                  <th className="p-3.5">Server 1 Served</th>
                  <th className="p-3.5">Server 2 Served</th>
                  <th className="p-3.5">Server 3 Served</th>
                  <th className="p-3.5">Avg Latency</th>
                  <th className="p-3.5">Avg Cluster Load</th>
                  <th className="p-3.5">Failures</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-800/80 text-slate-200">
                {benchmarkResults.map((res) => (
                  <tr key={res.algorithm} className="hover:bg-slate-900/50 transition-colors">
                    <td className="p-3.5 font-bold text-cyan-400">{res.algorithmName}</td>
                    <td className="p-3.5">{res.totalRequests} req</td>
                    <td className="p-3.5 text-emerald-400 font-bold">{res.requestsPerServer['Server 1'] || 0}</td>
                    <td className="p-3.5 text-emerald-400 font-bold">{res.requestsPerServer['Server 2'] || 0}</td>
                    <td className="p-3.5 text-emerald-400 font-bold">{res.requestsPerServer['Server 3'] || 0}</td>
                    <td className="p-3.5 text-amber-300 font-bold">{res.averageResponseTimeMs} ms</td>
                    <td className="p-3.5 text-purple-300 font-bold">{res.averageServerLoadPercent}%</td>
                    <td className="p-3.5">
                      {res.failedRequests > 0 ? (
                        <span className="text-red-400 font-bold">{res.failedRequests}</span>
                      ) : (
                        <span className="text-emerald-400 font-bold">0</span>
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>

          <div className="flex items-start space-x-2.5 bg-slate-950/80 border border-slate-800 p-3.5 rounded-xl text-xs text-slate-400">
            <Info className="w-4 h-4 text-cyan-400 shrink-0 mt-0.5" />
            <p className="leading-relaxed">
              <strong className="text-slate-200 font-mono">Simulation Disclaimer:</strong> These metrics are generated by deterministic algorithmic simulations to demonstrate comparative traffic distribution patterns under uniform synthetic workloads.
            </p>
          </div>
        </div>
      ) : (
        <div className="text-center py-10 border border-dashed border-slate-800 rounded-xl bg-slate-950/40">
          <p className="text-slate-400 text-xs font-mono">
            Click &quot;RUN BENCHMARK&quot; above to execute a simulated workload comparison test.
          </p>
        </div>
      )}
    </div>
  );
};
